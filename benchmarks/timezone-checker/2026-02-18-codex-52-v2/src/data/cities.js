const REGION_MAP = {
  Africa: 'Africa',
  America: 'Americas',
  Antarctica: 'Antarctica',
  Arctic: 'Arctic',
  Asia: 'Asia',
  Atlantic: 'Atlantic',
  Australia: 'Australia',
  Europe: 'Europe',
  Indian: 'Indian Ocean',
  Pacific: 'Pacific',
}

const AUTO_IANA_CITIES = typeof Intl.supportedValuesOf === 'function'
  ? Intl.supportedValuesOf('timeZone')
      .filter((timeZone) => !timeZone.startsWith('Etc/'))
      .map((timeZone) => {
        const parts = timeZone.split('/')
        const cityPart = parts[parts.length - 1]
        if (!cityPart || cityPart.startsWith('+') || cityPart.startsWith('-')) {
          return null
        }

        return [
          cityPart.replace(/_/g, ' '),
          REGION_MAP[parts[0]] || parts[0],
          timeZone,
        ]
      })
      .filter(Boolean)
  : []

function toObject([city, country, timeZone]) {
  return { city, country, timeZone }
}

function uniqueCities(cityList) {
  const seen = new Set()
  const unique = []

  cityList.forEach((entry) => {
    const key = `${entry.city.toLowerCase()}|${entry.country.toLowerCase()}|${entry.timeZone}`
    if (!seen.has(key)) {
      seen.add(key)
      unique.push(entry)
    }
  })

  return unique
}

