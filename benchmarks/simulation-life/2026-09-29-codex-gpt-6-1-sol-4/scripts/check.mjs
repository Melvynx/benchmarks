import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFile } from 'node:fs/promises';
import { Garden, BASE, PRESETS } from '../simulation.js';
for (const file of ['app.js', 'simulation.js', 'renderer.js', 'charts.js', 'server.mjs']) execFileSync(process.execPath, ['--check', file]);
const html = await readFile('index.html', 'utf8');
assert.match(html, /<title>GPT-6<\/title>/);
assert.match(html, /<h1>GPT-6<\/h1>/);
assert.match(await readFile('package.json', 'utf8'), /9189/);
const a = new Garden(BASE), b = new Garden(BASE);
a.advance(30); b.advance(30);
assert.deepEqual(a.history, b.history, 'A seed must reproduce the same run');
const changedSeed = new Garden({ ...BASE, seed: 42 }); changedSeed.advance(30);
assert.notDeepEqual(a.history, changedSeed.history, 'A different seed must change the run');
const resting = new Garden({ ...BASE, blues: 1, reds: 0, trees: 1, blueUse: 1, blueVision: 1 });
resting.blobs[0].pause = 2;
const energy = resting.blobs[0].energy; resting.advance(1);
assert(resting.blobs[0].energy < energy, 'Waiting costs energy');
assert.equal(resting.bites, 0, 'Resting blobs cannot eat');
const plant = resting.trees[0]; plant.fruit = 0; plant.delay = 2; resting.advance(1);
assert.equal(plant.fruit, 0, 'Fruit waits for its return delay'); resting.advance(2);
assert(plant.fruit > 0, 'Fruit grows again after the delay');
const contact = new Garden({ ...BASE, blues: 1, reds: 1, trees: 1 });
contact.blobs.forEach(blob => { blob.x = 0; blob.y = 0; blob.energy = 60; });
contact.blobs[0].immunity = 0; contact.update(.1);
assert.equal(contact.contacts, 1, 'Nearby reds contact blues');
assert(contact.blobs[0].energy < 30, 'Contact costs blue energy');
contact.advance(1);
assert.equal(contact.contacts, 1, 'Contact pause prevents instant repeat interactions');
const run = (key, seconds) => { const g = new Garden({ ...BASE, ...PRESETS[key].values }); g.advance(seconds); return g; };
const balanced = run('balanced', 900), abundant = run('abundant', 120), scarce = run('scarce', 360), heavy = run('redheavy', 150);
assert(balanced.counts().blue > 0 && balanced.counts().red > 0, 'Balanced garden should support both groups for a long run');
const maximum = (g, key) => Math.max(...g.history.map(h => h[key]));
assert(maximum(abundant, 'blue') > maximum(balanced, 'blue'), 'More fruit should support more blues');
assert(maximum(scarce, 'blue') < maximum(balanced, 'blue'), 'Low fruit should keep populations smaller');
assert(heavy.history.some(h => h.time < 60 && h.blue < BASE.blues / 2), 'A red-heavy start should cause an early blue dip');
assert(heavy.counts().red < maximum(heavy, 'red'), 'Reds should decline after the blue dip');
assert(maximum(balanced, 'blue') < 120 && maximum(balanced, 'red') < 100, 'Finite energy should prevent runaway growth');
const bluePeak = balanced.history.reduce((best, h) => h.blue > best.blue ? h : best, balanced.history[0]);
const earlyRedPeak = balanced.history.filter(h => h.time < 120).reduce((best, h) => h.red > best.red ? h : best, balanced.history[0]);
assert(earlyRedPeak.time > bluePeak.time, 'Early red peak should follow the blue peak');
const later = balanced.history.filter(h => h.time > 200);
assert(Math.max(...later.map(h => h.blue)) - Math.min(...later.map(h => h.blue)) >= 8, 'Blue population should continue rising and falling');
for (const g of [balanced, abundant, scarce, heavy]) {
  assert(g.births.blue + g.births.red > 0, 'Stored energy should create new lives');
  assert(g.blobs.every(b => Number.isFinite(b.energy) && b.energy > 0 && Math.hypot(b.x, b.y) < g.config.worldSize * 1.1));
  assert(g.trees.every(t => t.fruit >= 0 && t.fruit <= g.config.fruitLimit));
}
console.log('PASS: syntax, model titles, port, seeded reproducibility, energy costs, delayed regrowth, contact cooldowns, and four preset behavior checks.');
console.log(JSON.stringify({balanced:{seconds:balanced.time,population:balanced.counts(),bluePeak:bluePeak.blue,redPeak:maximum(balanced,'red')},abundantBluePeak:maximum(abundant,'blue'),lowFruitBluePeak:maximum(scarce,'blue'),redHeavyFinal:heavy.counts()},null,2));

await import('./ui-check.mjs');
