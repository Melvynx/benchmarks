// Builds src/lib/icon-paths.ts from the Material Symbols SVGs, keeping only icons referenced in src/.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const iconDir = join(root, "node_modules/@material-symbols/svg-400/outlined");
const outFile = join(root, "src/lib/icon-paths.ts");

function walk(dir, acc = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, acc);
    else if (/\.(ts|tsx)$/.test(name) && p !== outFile) acc.push(p);
  }
  return acc;
}

const names = new Set();
for (const file of walk(join(root, "src"))) {
  const src = readFileSync(file, "utf8");
  for (const m of src.matchAll(/["'`]([a-z0-9]+(?:_[a-z0-9]+)*)["'`]/g)) names.add(m[1]);
}

// Font ligature aliases that have no SVG of their own.
const ALIASES = { expand_more: "keyboard_arrow_down", expand_less: "keyboard_arrow_up" };

const paths = (file) => [...readFileSync(file, "utf8").matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join("|");

const entries = [];
for (const name of [...names].sort()) {
  const file = ALIASES[name] ?? name;
  const outline = join(iconDir, `${file}.svg`);
  if (!existsSync(outline)) continue;
  const o = paths(outline);
  const fillFile = join(iconDir, `${file}-fill.svg`);
  const f = existsSync(fillFile) ? paths(fillFile) : o;
  const key = /^[a-z_]/.test(name) ? name : JSON.stringify(name);
  entries.push(f === o ? `  ${key}: [${JSON.stringify(o)}],` : `  ${key}: [${JSON.stringify(o)}, ${JSON.stringify(f)}],`);
}

const body = `// Generated by scripts/gen-icons.mjs. Do not edit.
// Material Symbols Outlined (weight 400), Apache License 2.0.
export const ICON_PATHS: Record<string, readonly [outline: string, fill?: string]> = {
${entries.join("\n")}
};
`;

const prev = existsSync(outFile) ? readFileSync(outFile, "utf8") : "";
if (prev !== body) writeFileSync(outFile, body);
console.log(`icons: ${entries.length} (${(body.length / 1024).toFixed(1)} KB)`);
