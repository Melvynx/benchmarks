export function downloadAttachment(att: Attachment): void {
  const content = [
    `${att.name}`,
    ``,
    `This is a demo attachment generated by Fable Mail.`,
    `Kind: ${att.kind}  ·  Reported size: ${formatSize(att.size)}`,
  ].join('\n')
  const blob = new Blob([content], { type: 'text/plain' })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = att.name.replace(/\.[a-z0-9]+$/i, '') + '.txt'
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 5000)
}

export function kindFromFilename(name: string): AttachmentKind {
  const ext = name.split('.').pop()?.toLowerCase() ?? ''
  if (['png', 'jpg', 'jpeg', 'gif', 'webp', 'svg', 'heic', 'fig'].includes(ext)) return 'image'
  if (ext === 'pdf') return 'pdf'
  if (['xls', 'xlsx', 'csv', 'numbers'].includes(ext)) return 'sheet'
  if (['doc', 'docx', 'txt', 'md', 'pages', 'rtf'].includes(ext)) return 'doc'
  if (['ppt', 'pptx', 'key'].includes(ext)) return 'slides'
  if (['zip', 'tar', 'gz', 'rar', '7z'].includes(ext)) return 'zip'
  if (['js', 'ts', 'tsx', 'py', 'json', 'html', 'css', 'sh'].includes(ext)) return 'code'
  if (['mp4', 'mov', 'webm', 'mkv'].includes(ext)) return 'video'
  if (['mp3', 'wav', 'm4a', 'flac'].includes(ext)) return 'audio'
  if (['ics', 'ical'].includes(ext)) return 'calendar'
  return 'doc'
}

export function isValidEmail(value: string): boolean {
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(value.trim())
}

export function contactFromInput(value: string): Contact {
  const trimmed = value.trim().replace(/[,;]$/, '')
  const match = trimmed.match(/^(.*)<([^>]+)>$/)
  if (match) {
    return { name: match[1].trim() || match[2].trim(), email: match[2].trim() }
  }
  const namePart = trimmed.split('@')[0].replace(/[._-]+/g, ' ')
  const name = namePart.replace(/\b\w/g, (c) => c.toUpperCase())
  return { name, email: trimmed }
}

export function escapeHtml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

/** Convert plain text (double-newline paragraphs) into simple HTML. */
export function textToHtml(text: string): string {
  return text
    .split(/\n{2,}/)
    .map((p) => `<p>${escapeHtml(p.trim()).replace(/\n/g, '<br>')}</p>`)
    .join('')
}

export function htmlToText(html: string): string {
  const el = document.createElement('div')
  el.innerHTML = html
  return (el.textContent ?? '').replace(/\s+/g, ' ').trim()
}

export function snippetOf(html: string, max = 140): string {
  const text = html
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/\s+/g, ' ')
    .trim()
  return text.length > max ? text.slice(0, max - 1) + '…' : text
}

export function pluralize(n: number, word: string): string {
  return `${n} ${word}${n === 1 ? '' : 's'}`
}
