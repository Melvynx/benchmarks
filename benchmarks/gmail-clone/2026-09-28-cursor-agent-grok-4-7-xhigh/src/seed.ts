function at(now: number, daysAgo: number, hour: number, minute = 0): number {
  const date = new Date(now);
  date.setDate(date.getDate() - daysAgo);
  date.setHours(hour, minute, 0, 0);
  return date.getTime();
}

function ahead(now: number, days: number, hour: number, minute = 0): number {
  const date = new Date(now);
  date.setDate(date.getDate() + days);
  date.setHours(hour, minute, 0, 0);
  return date.getTime();
}

function msg(
  id: string,
  from: Person,
  to: Person[],
  date: number,
  body: string,
  extra: Partial<Message> = {},
): Message {
  return {
    id,
    from,
    to,
    cc: extra.cc ?? [],
    bcc: extra.bcc ?? [],
    date,
    body,
    format: extra.format ?? "text",
    attachments: extra.attachments ?? [],
    unread: extra.unread ?? false,
  };
}

function file(id: string, filename: string, mime: string, size: number, text: string): Attachment {
  return { id, filename, mime, size, text };
}

