import { chromium } from 'playwright-core'
const b = await chromium.launch({ channel: 'chrome' })
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage()
const errs = []
p.on('pageerror', (e) => errs.push(e.message))
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()))
const ok = (c, m) => console.log(c ? 'PASS' : 'FAIL', m)
await p.goto('http://localhost:9361/')
// theme + density
await p.getByRole('button', { name: 'Settings' }).click()
await p.locator('.seg button', { hasText: 'dark' }).click()
ok((await p.evaluate(() => document.documentElement.dataset.theme)) === 'dark', 'dark theme')
await p.locator('.seg button', { hasText: 'compact' }).click()
ok(await p.locator('.app.d-compact').count() === 1, 'compact density')
await p.locator('.seg button', { hasText: 'light' }).click()
await p.keyboard.press('Escape')
// snooze
await p.locator('.row', { hasText: 'Lunch Thursday' }).locator('.chk').click()
await p.getByRole('button', { name: 'Snooze' }).first().click()
await p.locator('.sched .mitem', { hasText: 'Tomorrow' }).click()
await p.getByRole('link', { name: /Snoozed/ }).click()
ok(await p.locator('.row', { hasText: 'Lunch Thursday' }).count() === 1, 'snoozed list')
// new label via sidebar
await p.getByRole('button', { name: 'Create new label' }).click()
await p.locator('input[aria-label="New label name"]').fill('Ideas')
await p.keyboard.press('Enter')
ok(await p.getByRole('link', { name: /Ideas/ }).count() === 1, 'label created')
// schedule send
await p.locator('.compose-btn').click()
await p.locator('input[aria-label="To"]').fill('tom.bennett@outlook.com')
await p.keyboard.press('Enter')
await p.locator('input[aria-label="Subject"]').fill('Scheduled hi')
await p.getByRole('button', { name: 'More send options' }).click()
await p.locator('.sched .mitem', { hasText: 'Tomorrow morning' }).click()
await p.getByRole('link', { name: /Scheduled/ }).click()
ok(await p.locator('.row', { hasText: 'Scheduled hi' }).count() === 1, 'scheduled list')
// no recipient error
await p.getByRole('link', { name: /Inbox/ }).click()
await p.locator('.compose-btn').click()
await p.getByRole('button', { name: 'Send', exact: true }).click()
ok(await p.getByText('Please specify at least one recipient').count() > 0, 'recipient validation')
// quick reply auto-reply
await p.locator('.c-head button[title="Save & close"]').click()
await p.getByRole('link', { name: /Inbox/ }).click()
await p.locator('.row', { hasText: 'Lunch' }).count()
await p.locator('.row', { hasText: 'Design review' }).count()
await p.getByRole('link', { name: /All Mail/ }).click()
await p.locator('.row', { hasText: 'Design review' }).click()
await p.getByRole('button', { name: 'Sounds good!' }).click()
ok(await p.getByText('Message sent').count() > 0, 'smart reply sent')
await p.waitForTimeout(10500)
ok(await p.locator('.msg').count() >= 3, 'auto reply arrived')
// mobile drawer
const mp = await (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage()
await mp.goto('http://localhost:9361/')
await mp.getByRole('button', { name: 'Main menu' }).click()
await mp.getByRole('link', { name: /Starred/ }).click()
ok(await mp.locator('.row').count() > 0, 'mobile drawer nav')
console.log(errs.length ? errs : 'no errors')
await b.close()
