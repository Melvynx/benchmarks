import { chromium } from 'playwright-core'
const b = await chromium.launch({ channel: 'chrome' })
const errs = []
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } })
const p = await ctx.newPage()
p.on('pageerror', (e) => errs.push('PAGEERR ' + e.message))
p.on('console', (m) => m.type() === 'error' && errs.push('CONSOLE ' + m.text()))
const ok = (c, m) => console.log(c ? 'PASS' : 'FAIL', m)
await p.goto('http://localhost:9361/')
ok((await p.title()) === 'Claude Sonnet 5.5', 'title')
await p.screenshot({ path: 'shots/inbox.png' })
const rows = () => p.locator('.row').count()
console.log('rows', await rows())
// open thread, read
await p.locator('.row', { hasText: 'Q4 roadmap' }).click()
ok(await p.locator('.t-subject').innerText().then((t) => t.includes('Q4 roadmap')), 'open thread')
await p.screenshot({ path: 'shots/thread.png' })
await p.locator('.msg.collapsed').first().click()
// star + archive
await p.getByRole('button', { name: 'Archive (e)' }).click()
ok(!(await p.locator('.row', { hasText: 'Q4 roadmap' }).count()), 'archived removed from inbox')
await p.getByRole('button', { name: 'Undo' }).click()
ok(await p.locator('.row', { hasText: 'Q4 roadmap' }).count() === 1, 'undo archive')
// select + delete
await p.locator('.row', { hasText: 'Lunch Thursday' }).locator('.chk').click()
await p.getByRole('button', { name: 'Delete (#)' }).click()
await p.getByRole('link', { name: /Trash/ }).click()
ok(await p.locator('.row', { hasText: 'Lunch Thursday' }).count() === 1, 'in trash')
// label
await p.getByRole('link', { name: /Inbox/ }).click()
await p.locator('.row', { hasText: 'Dentist' }).locator('.chk').click()
await p.getByRole('button', { name: 'Labels' }).click()
await p.locator('.labelmenu .mitem', { hasText: 'Travel' }).click()
ok(await p.locator('.row', { hasText: 'Dentist' }).locator('.lchip', { hasText: 'Travel' }).count() === 1, 'label applied')
// search
await p.locator('input[aria-label="Search mail"]').fill('from:priya has:attachment')
await p.keyboard.press('Enter')
console.log('search rows', await rows())
await p.screenshot({ path: 'shots/search.png' })
// compose + send
await p.keyboard.press('Escape')
await p.getByRole('link', { name: /Inbox/ }).click()
await p.locator('.compose-btn').click()
await p.locator('input[aria-label="To"]').fill('marc')
await p.screenshot({ path: 'shots/compose.png' })
await p.keyboard.press('Enter')
await p.locator('input[aria-label="Subject"]').fill('Hello from test')
await p.locator('.c-body').click()
await p.keyboard.type('Testing body text')
await p.getByRole('button', { name: 'Send', exact: true }).click()
ok(await p.getByText('Message sent').count() > 0, 'sent toast')
await p.getByRole('link', { name: /Sent/ }).click()
ok(await p.locator('.row', { hasText: 'Hello from test' }).count() === 1, 'in sent')
// draft
await p.locator('.compose-btn').click()
await p.locator('input[aria-label="Subject"]').fill('Draft subj')
await p.locator('.c-head button[title="Save & close"]').click()
await p.getByRole('link', { name: /Drafts/ }).click()
ok(await p.locator('.row', { hasText: 'Draft subj' }).count() === 1, 'draft saved')
await p.waitForTimeout(500); await p.reload()
await p.getByRole('link', { name: /Drafts/ }).click()
ok(await p.locator('.row', { hasText: 'Draft subj' }).count() === 1, 'persisted')
// keyboard
await p.getByRole('link', { name: /Inbox/ }).click()
await p.keyboard.press('j'); await p.keyboard.press('Enter')
ok(await p.locator('.thread').count() === 1, 'kb open')
await p.keyboard.press('r')
ok(await p.locator('.compose').count() >= 1, 'reply compose')
await p.screenshot({ path: 'shots/reply.png' })
// mobile
const m = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })
const mp = await m.newPage()
mp.on('pageerror', (e) => errs.push('MPAGEERR ' + e.message))
await mp.goto('http://localhost:9361/')
await mp.screenshot({ path: 'shots/m-inbox.png' })
await mp.locator('.row').first().click()
await mp.screenshot({ path: 'shots/m-thread.png' })
await mp.goBack()
await mp.locator('.fab').click()
await mp.screenshot({ path: 'shots/m-compose.png' })
console.log(errs.length ? errs : 'no errors')
await b.close()
