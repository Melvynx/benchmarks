const date = (days: number, hour = 10, minute = 0) => {
  const d = new Date();
  d.setDate(d.getDate() - days);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
};
const attachment = (name: string, size: string): Attachment => ({
  id: name,
  name,
  size,
  type: name.split(".").pop() || "file",
});

