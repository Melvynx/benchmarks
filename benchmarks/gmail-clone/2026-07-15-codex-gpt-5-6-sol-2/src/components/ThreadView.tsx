import {
  Archive,
  ArrowLeft,
  ChevronDown,
  ChevronUp,
  Clock3,
  Download,
  FileArchive,
  FileImage,
  FileSpreadsheet,
  FileText,
  Forward,
  Mail,
  MoreVertical,
  Printer,
  Reply,
  RotateCcw,
  Star,
  Tag,
  Trash2,
} from 'lucide-react';
import { useEffect, useState } from 'react';

import type { Attachment, MailThread } from '../domain/mail';
import { formatFullDate } from '../lib/format';
import { Avatar } from './Avatar';
import { IconButton } from './IconButton';

interface ThreadViewProps {
  thread: MailThread;
  labels: readonly string[];
  onBack: () => void;
  onArchive: () => void;
  onTrash: () => void;
  onToggleRead: () => void;
  onStar: () => void;
  onSnooze: () => void;
  onLabel: (label: string) => void;
  onRestore: () => void;
  onDeleteForever: () => void;
  onReply: () => void;
  onForward: () => void;
  onNotify: (message: string) => void;
}

function AttachmentIcon({ attachment }: { attachment: Attachment }) {
  if (attachment.kind === 'image') return <FileImage aria-hidden="true" />;
  if (attachment.kind === 'sheet') return <FileSpreadsheet aria-hidden="true" />;
  if (attachment.kind === 'archive') return <FileArchive aria-hidden="true" />;
  return <FileText aria-hidden="true" />;
}

function downloadAttachment(attachment: Attachment): void {
  const content = `Local preview file: ${attachment.name}\nGenerated by GPT-5.6 Sol.`;
  const url = URL.createObjectURL(new Blob([content], { type: 'text/plain' }));
  const link = document.createElement('a');
  link.href = url;
  link.download = attachment.name;
  link.click();
  URL.revokeObjectURL(url);
}

export function ThreadView({
  thread,
  labels,
  onBack,
  onArchive,
  onTrash,
  onToggleRead,
  onStar,
  onSnooze,
  onLabel,
  onRestore,
  onDeleteForever,
  onReply,
  onForward,
  onNotify,
}: ThreadViewProps) {
  const lastMessageId = thread.messages.at(-1)?.id;
  const [expandedMessageIds, setExpandedMessageIds] = useState<Set<string>>(
    () => new Set(lastMessageId ? [lastMessageId] : []),
  );
  const [isLabelMenuOpen, setIsLabelMenuOpen] = useState(false);
  const canArchive = thread.folder === 'inbox';
  const canSnooze = thread.folder === 'inbox' || thread.folder === 'archive';

  useEffect(() => {
    setExpandedMessageIds(new Set(lastMessageId ? [lastMessageId] : []));
  }, [lastMessageId, thread.id]);

  const toggleExpanded = (messageId: string) => {
    setExpandedMessageIds((current) => {
      const next = new Set(current);
      if (next.has(messageId)) next.delete(messageId);
      else next.add(messageId);
      return next;
    });
  };

  return (
    <section className="thread-view" aria-label={`Conversation: ${thread.subject}`}>
      <div className="thread-toolbar">
        <div className="thread-toolbar__group">
          <IconButton label="Back to mailbox" onClick={onBack}>
            <ArrowLeft aria-hidden="true" />
          </IconButton>
          {thread.folder === 'trash' ? (
            <>
              <button type="button" className="toolbar-text-action" onClick={onDeleteForever}>
                Delete forever
              </button>
              <button type="button" className="toolbar-text-action" onClick={onRestore}>
                <RotateCcw aria-hidden="true" />
                Restore
              </button>
            </>
          ) : (
            <>
              {canArchive ? (
                <IconButton label="Archive" onClick={onArchive}>
                  <Archive aria-hidden="true" />
                </IconButton>
              ) : null}
              <IconButton label="Delete" onClick={onTrash}>
                <Trash2 aria-hidden="true" />
              </IconButton>
              <IconButton label={thread.isRead ? 'Mark as unread' : 'Mark as read'} onClick={onToggleRead}>
                <Mail aria-hidden="true" />
              </IconButton>
              {canSnooze ? (
                <IconButton label="Snooze" onClick={onSnooze}>
                  <Clock3 aria-hidden="true" />
                </IconButton>
              ) : null}
              <div className="menu-anchor">
                <IconButton
                  label="Labels"
                  aria-expanded={isLabelMenuOpen}
                  onClick={() => setIsLabelMenuOpen((open) => !open)}
                >
                  <Tag aria-hidden="true" />
                </IconButton>
                {isLabelMenuOpen ? (
                  <div className="label-menu popover" role="menu">
                    <strong>Label as</strong>
                    {labels.map((label) => (
                      <button
                        type="button"
                        role="menuitemcheckbox"
                        aria-checked={thread.labels.includes(label)}
                        key={label}
                        onClick={() => {
                          onLabel(label);
                          setIsLabelMenuOpen(false);
                        }}
                      >
                        <span className={`menu-check${thread.labels.includes(label) ? ' menu-check--active' : ''}`} />
                        {label}
                      </button>
                    ))}
                  </div>
                ) : null}
              </div>
              <IconButton label="More" onClick={() => onNotify('Conversation details copied to the local activity log.')}>
                <MoreVertical aria-hidden="true" />
              </IconButton>
            </>
          )}
        </div>
        <div className="thread-toolbar__group thread-toolbar__desktop-actions">
          <IconButton label="Print conversation" onClick={() => window.print()}>
            <Printer aria-hidden="true" />
          </IconButton>
        </div>
      </div>

      <div className="thread-scroll">
        <header className="thread-subject">
          <h2>{thread.subject || '(no subject)'}</h2>
          <div className="thread-subject__labels">
            {thread.labels.map((label) => (
              <span className={`label-chip label-chip--${label.toLocaleLowerCase()}`} key={label}>
                {label}
              </span>
            ))}
          </div>
          <IconButton
            label={thread.isStarred ? 'Remove star' : 'Add star'}
            className={thread.isStarred ? 'star-button star-button--active' : 'star-button'}
            aria-pressed={thread.isStarred}
            onClick={onStar}
          >
            <Star aria-hidden="true" fill={thread.isStarred ? 'currentColor' : 'none'} />
          </IconButton>
        </header>

        <div className="conversation">
          {thread.messages.map((message, index) => {
            const isExpanded = expandedMessageIds.has(message.id);
            return (
              <article
                className={`message-card${isExpanded ? ' message-card--expanded' : ''}`}
                key={message.id}
              >
                <button
                  type="button"
                  className="message-card__header"
                  onClick={() => toggleExpanded(message.id)}
                  aria-expanded={isExpanded}
                >
                  <Avatar contact={message.sender} size="medium" />
                  <span className="message-card__identity">
                    <strong>{message.sender.name}</strong>
                    <span className="message-card__email">&lt;{message.sender.email}&gt;</span>
                    {!isExpanded ? <span className="message-card__summary">{message.body[0]}</span> : null}
                  </span>
                  <span className="message-card__meta">
                    <time dateTime={message.timestamp}>{formatFullDate(message.timestamp)}</time>
                    {isExpanded ? <ChevronUp aria-hidden="true" /> : <ChevronDown aria-hidden="true" />}
                  </span>
                </button>

                {isExpanded ? (
                  <div className="message-card__content">
                    <div className="message-card__recipient-line">
                      to {message.recipients.map((recipient) => recipient.name).join(', ')}
                    </div>
                    <div className="message-body">
                      {message.body.map((paragraph, paragraphIndex) => (
                        <p key={`${message.id}-${paragraphIndex}`}>{paragraph}</p>
                      ))}
                    </div>
                    {message.attachments.length > 0 ? (
                      <div className="attachment-grid" aria-label="Message attachments">
                        {message.attachments.map((attachment) => (
                          <button
                            type="button"
                            className="attachment-card"
                            key={attachment.id}
                            onClick={() => downloadAttachment(attachment)}
                          >
                            <span
                              className="attachment-card__preview"
                              style={{ backgroundColor: attachment.accent }}
                            >
                              <AttachmentIcon attachment={attachment} />
                            </span>
                            <span className="attachment-card__details">
                              <strong>{attachment.name}</strong>
                              <span>{attachment.size}</span>
                            </span>
                            <Download aria-hidden="true" />
                          </button>
                        ))}
                      </div>
                    ) : null}
                    {index === thread.messages.length - 1 ? (
                      <div className="message-inline-actions">
                        <button type="button" className="outline-button" onClick={onReply}>
                          <Reply aria-hidden="true" />
                          Reply
                        </button>
                        <button type="button" className="outline-button" onClick={onForward}>
                          <Forward aria-hidden="true" />
                          Forward
                        </button>
                      </div>
                    ) : null}
                  </div>
                ) : null}
              </article>
            );
          })}
        </div>

        <button type="button" className="quick-reply" onClick={onReply}>
          <Reply aria-hidden="true" />
          <span>Reply to this conversation</span>
        </button>
      </div>
    </section>
  );
}
