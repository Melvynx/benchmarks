import { chromium } from "playwright";
const out = new globalThis.URL("../.shots/", import.meta.url).pathname;
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => m.type() === "error" && errors.push(m.text()));
const log = (n, ok, x = "") => console.log(`${ok ? "PASS" : "FAIL"}  ${n}${x ? `  (${x})` : ""}`);
await page.goto("http://localhost:9391/", { waitUntil: "networkidle" });
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: "networkidle" });
await page.waitForSelector("[role=grid] [data-thread-id]");
await page.getByRole("button", { name: "Compose" }).first().click();
await page.waitForTimeout(500);
const c = page.locator("[data-composer]").last();
await c.getByLabel("To", { exact: true }).fill("Sofia Alvarez <sofia@fieldwork.co>, theo@fieldwork.co");
await c.getByLabel("Subject").click();
log("paste-style multi recipients → chips", (await c.getByRole("button", { name: /^Remove (Sofia Alvarez|Theo Martin)$/ }).count()) === 2);
await c.getByLabel("Subject").fill("Specs attached");
await c.locator("input[type=file]").setInputFiles({ name: "release-notes.txt", mimeType: "text/plain", buffer: Buffer.from("Release 4.2\n- Faster inbox\n- Snooze suggestions\n") });
await page.waitForTimeout(400);
log("attachment chip", await c.getByText("release-notes.txt").isVisible());
await c.locator(".ProseMirror").click();
await page.keyboard.type("Notes attached.");
await page.screenshot({ path: out + "u-compose.png" });
await c.getByRole("button", { name: "Send", exact: true }).click();
await page.waitForTimeout(6500);
await page.evaluate(() => (location.hash = "sent"));
await page.waitForTimeout(300);
await page.locator("[role=grid] [data-thread-id]", { hasText: "Specs attached" }).first().locator("[data-subject]").click();
await page.waitForTimeout(400);
const tile = page.getByRole("button", { name: "Preview release-notes.txt" });
log("sent message shows attachment", await tile.isVisible());
await tile.hover();
const [dl] = await Promise.all([page.waitForEvent("download", { timeout: 6000 }).catch(() => null), tile.getByRole("button", { name: "Download release-notes.txt" }).click()]);
if (dl) {
  const { readFileSync } = await import("node:fs");
  const text = readFileSync(await dl.path(), "utf8");
  log("uploaded bytes round-trip via IndexedDB", text.startsWith("Release 4.2"), JSON.stringify(text.slice(0, 20)));
} else log("uploaded bytes round-trip via IndexedDB", false, "no download");
await page.screenshot({ path: out + "u-sent.png" });
log("no runtime errors", errors.length === 0, errors.slice(0, 2).join(" | "));
await browser.close();
