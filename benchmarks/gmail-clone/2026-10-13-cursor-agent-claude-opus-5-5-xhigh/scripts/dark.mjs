import { chromium } from "playwright";
const out = new globalThis.URL("../.shots/", import.meta.url).pathname;
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 820 }, colorScheme: "dark" });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
await page.goto("http://localhost:9391/", { waitUntil: "networkidle" });
await page.evaluate(() => {
  localStorage.clear();
});
await page.reload({ waitUntil: "networkidle" });
await page.getByRole("button", { name: "Settings" }).first().click();
await page.getByRole("button", { name: /^system$/i }).click();
await page.getByRole("button", { name: "Close" }).first().click();
await page.waitForSelector("[role=grid] [data-thread-id]");
await page.screenshot({ path: out + "dk-inbox.png" });
await page.evaluate(() => (location.hash = "category/promotions"));
await page.waitForTimeout(300);
await page.locator("[role=grid] [data-thread-id] [data-subject]").first().click();
await page.waitForTimeout(400);
await page.screenshot({ path: out + "dk-promo.png" });
await page.getByRole("button", { name: "Compose" }).first().click();
await page.waitForTimeout(500);
await page.screenshot({ path: out + "dk-compose.png" });
await page.keyboard.press("Escape");
await page.evaluate(() => (location.hash = "search/zzzzqqq"));
await page.waitForTimeout(400);
await page.screenshot({ path: out + "dk-empty.png" });
console.log("dark:", await page.evaluate(() => document.documentElement.classList.contains("dark")), "errors", errors.length ? errors : "none");
await browser.close();
