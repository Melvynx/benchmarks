import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
await page.goto('http://127.0.0.1:9372/', { waitUntil: 'networkidle' })
const check = (c, m) => console.log((c ? 'PASS ' : 'FAIL ') + m)
await page.getByRole('row').nth(1).click()
await page.getByRole('button', { name: 'Reply', exact: true }).last().click()
await page.waitForTimeout(300)
check(await page.getByLabel('Subject').inputValue().then((v) => v.startsWith('Re: ')), 'reply prefills Re: subject')
check(await page.getByLabel('Message body').innerText().then((t) => t.includes('wrote:')), 'reply quotes original')
await page.getByRole('button', { name: 'Send', exact: true }).click()
await page.waitForTimeout(9500)
check(await page.getByText(/New reply from/).isVisible().catch(() => false), 'simulated reply arrives after sending')
// snooze
await page.getByRole('row').nth(2).click()
await page.locator('[aria-label="Conversation"]').getByTitle('Snooze (b)').click()
await page.getByRole('menuitemcheckbox', { name: /Later today/ }).click()
await page.waitForTimeout(300)
await page.getByRole('button', { name: /^Snoozed/ }).first().click()
await page.waitForTimeout(200)
check((await page.getByRole('row').count()) >= 1, 'snoozed view lists snoozed conversation')
// label create from list selection
await page.getByRole('button', { name: /^Inbox/ }).first().click()
await page.getByRole('row').nth(0).getByRole('checkbox', { name: 'Select conversation' }).click()
await page.getByTitle('Label as (l)').first().click()
await page.getByPlaceholder('New label').fill('Urgent')
await page.getByPlaceholder('New label').press('Enter')
await page.waitForTimeout(300)
check(await page.getByText('Urgent').first().isVisible(), 'created label appears in sidebar/list')
// 'Enter' on a dropdown search
await page.locator('#search-input').fill('is:unread')
await page.keyboard.press('Enter')
await page.waitForTimeout(200)
check(await page.getByText(/Results for/).isVisible(), 'is:unread search works')
console.log('errors:', errors)
await browser.close()
