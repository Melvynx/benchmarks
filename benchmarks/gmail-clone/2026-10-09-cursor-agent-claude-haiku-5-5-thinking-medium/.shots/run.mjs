import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errors = []
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message))
page.on('console', (m) => m.type() === 'error' && errors.push('console: ' + m.text()))
await page.goto('http://127.0.0.1:9372/', { waitUntil: 'networkidle' })
console.log('title:', await page.title())
await page.screenshot({ path: '.shots/1-inbox.png' })
// open first thread
await page.locator('[role=row]').first().click()
await page.waitForTimeout(300)
await page.screenshot({ path: '.shots/2-thread.png' })
// compose flow
await page.keyboard.press('c')
await page.waitForTimeout(200)
await page.getByLabel('To', { exact: true }).fill('sarah')
await page.waitForTimeout(200)
await page.screenshot({ path: '.shots/3-compose-suggest.png' })
await page.keyboard.press('Enter')
await page.getByLabel('Subject').fill('Test subject')
await page.getByLabel('Message body').click()
await page.keyboard.type('Hello team, quick test.')
await page.waitForTimeout(700)
await page.screenshot({ path: '.shots/4-compose.png' })
await page.getByRole('button', { name: 'Send', exact: true }).click()
await page.waitForTimeout(400)
await page.screenshot({ path: '.shots/5-sent-toast.png' })
// search
await page.locator('#search-input').fill('from:sarah has:attachment')
await page.keyboard.press('Enter')
await page.waitForTimeout(300)
await page.screenshot({ path: '.shots/6-search.png' })
console.log('errors:', errors.slice(0, 10))
await browser.close()
