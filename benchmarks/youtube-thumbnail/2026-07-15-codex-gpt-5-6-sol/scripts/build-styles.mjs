import { readFile, readdir, writeFile } from "node:fs/promises";
import { extname, join } from "node:path";
import { compile } from "tailwindcss";

const root = process.cwd();
const sourceExtensions = new Set([".ts", ".tsx", ".js", ".jsx"]);

async function collectFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await collectFiles(path)));
    } else if (sourceExtensions.has(extname(entry.name))) {
      files.push(path);
    }
  }

  return files;
}

const sourceFiles = [
  ...(await collectFiles(join(root, "app"))),
  ...(await collectFiles(join(root, "components"))),
  ...(await collectFiles(join(root, "lib"))),
];

const candidates = new Set();
const candidatePattern = /[!@\w\-:[\]()./%#]+/g;

for (const file of sourceFiles) {
  const source = await readFile(file, "utf8");
  for (const candidate of source.match(candidatePattern) ?? []) {
    candidates.add(candidate);
  }
}

const theme = await readFile(join(root, "node_modules/tailwindcss/theme.css"), "utf8");
const preflight = await readFile(join(root, "node_modules/tailwindcss/preflight.css"), "utf8");
const utilities = await readFile(join(root, "node_modules/tailwindcss/utilities.css"), "utf8");
const custom = await readFile(join(root, "app/styles.input.css"), "utf8");

const compiler = await compile(
  `@layer theme, base, components, utilities;\n${theme}\n${preflight}\n${utilities}\n${custom}`,
);
const output = compiler.build([...candidates]);

await writeFile(
  join(root, "app/globals.css"),
  `/* Generated by scripts/build-styles.mjs. */\n${output}\n`,
);
